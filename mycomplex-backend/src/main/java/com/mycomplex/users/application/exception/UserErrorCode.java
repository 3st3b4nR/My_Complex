package com.mycomplex.users.application.exception;

/** Stable error contract shared by the users application and REST adapter. */
public enum UserErrorCode {
    PROPERTY_MEMBER_NOT_FOUND,
    PROPERTY_MEMBER_VERSION_CONFLICT,
    LAST_PROPERTY_ADMINISTRATOR,
    INVALID_PROPERTY_MEMBER_UPDATE,
    INVALID_PROPERTY_MEMBER_REGISTRATION,
    USER_NOT_AVAILABLE,
    MEMBERSHIP_ALREADY_EXISTS,
    MEMBERSHIP_REQUIRES_REACTIVATION,
    DELETED_USER_REQUIRES_INTERVENTION,
    REGISTRATION_MODE_CONFLICT,
    DUPLICATE_USER_DATA,
    MEMBERSHIP_NOT_REACTIVATABLE,
    INVITATION_IN_PROGRESS,
    INVITATION_INVALID_STATE,
    INVITATION_RESEND_TOO_SOON,
    INVITATION_STATE_CONFLICT,
    AUTHENTICATED_IDENTITY_CONFLICT,
    AUTH0_NOT_CONFIGURED,
    AUTH0_CONFIGURATION_ERROR,
    AUTH0_PERMISSION_DENIED,
    AUTH0_RATE_LIMITED,
    AUTH0_UNAVAILABLE,
    AUTH0_INVITATION_UNAVAILABLE,
    AUTH0_IDENTITY_ALREADY_EXISTS,
    AUTH0_IDENTITY_CONFLICT,
    UNEXPECTED_ERROR;

    public String value() {
        return name();
    }

    public static UserErrorCode from(String value) {
        return UserErrorCode.valueOf(value);
    }
}
